// brain/entities/<kind folder>/index.md: one generated line per entity of that kind, so a person (or an agent
// listing a folder) sees who is there without opening every page. Written by the lib with the pages, through
// the same write path and in the same commit; never edited by hand (a hand edit is overwritten), and never
// read as an entity (lib/layout.mjs skips it).
import { existsSync, mkdirSync, readFileSync, writeFileSync, renameSync } from "node:fs";
import { join, dirname } from "node:path";
import { randomUUID } from "node:crypto";
import { DEFAULT_KINDS } from "./kinds.mjs";
import { kindFolder, kindFolders, indexPath, layout, linkFrom, shortId, INDEX_FILE, keepsIndexes, isKindPagePath } from "./layout.mjs";

export const INDEX_MARK = "<!-- generated by GTM Brain from the pages in this folder; edits here are overwritten -->";
const md = value => String(value).replace(/[\\`*_{}\[\]<>#|]/g, "\\$&").replace(/\r?\n/g, " ");
const title = folder => folder[0].toUpperCase() + folder.slice(1).replace(/-/g, " ");
const day = v => (typeof v === "string" && /^\d{4}-\d\d-\d\d/.test(v) ? v.slice(0, 10) : null);
const clip = (s, n = 110) => { const t = String(s || "").replace(/\s+/g, " ").trim(); return t.length > n ? t.slice(0, n - 3).trimEnd() + "..." : t; };

/* One line about the entity, from what was compiled: the first overview claim, else its compiled fields. */
export function oneLine(e) {
  const fm = e._fm || {};
  let brief = null; try { brief = fm.compilation ? JSON.parse(fm.compilation) : null; } catch {}
  const first = brief?.overview?.find(c => c && typeof c.text === "string" && c.text.trim());
  if (first) return clip(first.text);
  let fields = []; try { fields = fm.compiled_fields ? JSON.parse(fm.compiled_fields) : []; } catch {}
  if (Array.isArray(fields) && fields.length) return clip(fields.filter(f => f && f.text).map(f => `${f.field.replace(/_/g, " ")}: ${f.text}`).join("; "));
  return e.subtype ? e.subtype : "";
}

/* The index text for one kind folder: name (linked), one line, relation to us, short id, last mentioned. */
export function indexText(kind, entities, relations = new Map()) {
  const folder = kindFolder(kind), path = indexPath(kind);
  const rows = entities.filter(e => e._path && !e._fm?.redirect).sort((a, b) => a.name.localeCompare(b.name) || a.id.localeCompare(b.id));
  const line = e => {
    const parts = [`[${md(e.name)}](${encodeURI(linkFrom(path, e._path))})`];
    const about = oneLine(e); if (about) parts.push(md(about));
    const rel = relations.get(e.id); if (rel) parts.push(rel);
    parts.push(shortId(e.id));
    parts.push(day(e._fm?.latest_evidence_at) ? `last mentioned ${day(e._fm.latest_evidence_at)}` : "not mentioned in notes yet");
    return `- ${parts.join(" · ")}${e.status === "archived" ? " (archived)" : ""}`;
  };
  return [`# ${title(folder)}`, "", INDEX_MARK, "", `One line per ${kind.replace(/_/g, " ")}: name · what they are · relation to us · short id · last mentioned. Open a page for the cited brief.`, "",
    ...(rows.length ? rows.map(line) : [`No ${title(folder).toLowerCase()} yet: they arrive with the notes.`]), ""].join("\n");
}

const write = (path, text) => {
  if (existsSync(path) && readFileSync(path, "utf8") === text) return false;
  mkdirSync(dirname(path), { recursive: true });
  const tmp = `${path}.${randomUUID()}.tmp`; writeFileSync(tmp, text); renameSync(tmp, path); return true;
};
/* Rewrite the index of every kind folder in use (and the default kinds), in a brain with kind folders only.
   registry: lib.readNames (pages read once); relations: Map id -> relation to us (lib/relation-to-us.mjs). */
export function writeKindIndexes(root, registry, relations = new Map(), { kinds = [] } = {}) {
  if (!keepsIndexes(root)) return [];   // layout 4: the folder holds pages only; query entities lists a kind
  if (layout(root) !== "kinds" && !kinds.length) return [];
  const byKind = new Map();
  for (const k of [...DEFAULT_KINDS, ...kinds]) byKind.set(k, []);
  for (const e of registry) if (e._path && isKindPagePath(e._path)) { if (!byKind.has(e.kind)) byKind.set(e.kind, []); byKind.get(e.kind).push(e); }
  // a folder present whose kind has no entity left keeps an index too
  const present = new Set(kindFolders(root));
  const changed = [];
  for (const [kind, list] of byKind) {
    const rel = indexPath(kind);
    if (!present.has(kindFolder(kind)) && !list.length && !DEFAULT_KINDS.includes(kind) && !kinds.includes(kind)) continue;
    if (write(join(root, rel), indexText(kind, list, relations))) changed.push(rel);
  }
  return changed;
}
export { INDEX_FILE };
